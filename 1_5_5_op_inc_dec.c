#include <stdion.h>

int main(void)
{
       int a = 5;
       
       printf("Pre-increment = %d\n", ++a);
       
       printf("Post-increment = %d\n", a++);
       
       printf("After post-increment = %d\n", a);
       
       printf("Pre-decrement = %d\n", --a);
       
       printf("Post-Decrement = %d\n", a--);
       
       printf("After post-decrement = %d\n", a);
       
       return 0;
       
}       
